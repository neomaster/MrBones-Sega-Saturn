const uint8_t *mb_font_glyph(char ch) {
    unsigned char uc = (unsigned char)ch;
    if (uc < 0x20u || uc > 0x7Eu) uc = (unsigned char)'?';
    return k_font8x8[uc - 0x20u];
}

unsigned mb_font_text_width(const char *text, unsigned scale) {
    if (!text) return 0;
    if (scale == 0) scale = 1;
    return (unsigned)strlen(text) * 8u * scale;
}

void mb_font_draw_char(uint8_t *dst_rgba, unsigned dst_w, unsigned dst_h,
                       int x, int y, char ch,
                       uint8_t r, uint8_t g, uint8_t b, unsigned scale) {
    const uint8_t *rows;
    unsigned row, col, sy, sx;
    if (!dst_rgba || dst_w == 0 || dst_h == 0) return;
    if (scale == 0) scale = 1;
    rows = mb_font_glyph(ch);
    for (row = 0; row < 8u; row++) {
        uint8_t bits = rows[row];
        if (!bits) continue;
        for (col = 0; col < 8u; col++) {
            if ((bits & (0x80u >> col)) == 0) continue;
            for (sy = 0; sy < scale; sy++) {
                int py = y + (int)(row * scale + sy);
                if (py < 0 || (unsigned)py >= dst_h) continue;
                for (sx = 0; sx < scale; sx++) {
                    int px = x + (int)(col * scale + sx);
                    uint8_t *dst;
                    if (px < 0 || (unsigned)px >= dst_w) continue;
                    dst = &dst_rgba[((unsigned)py * dst_w + (unsigned)px) * 4u];
                    dst[0] = r;
                    dst[1] = g;
                    dst[2] = b;
                    dst[3] = 255u;
                }
            }
        }
    }
}

void mb_font_draw_text(uint8_t *dst_rgba, unsigned dst_w, unsigned dst_h,
                       int x, int y, const char *text,
                       uint8_t r, uint8_t g, uint8_t b, unsigned scale) {
    int cx = x;
    if (!dst_rgba || !text) return;
    if (scale == 0) scale = 1;
    while (*text) {
        if (*text == '\n') {
            cx = x;
            y += (int)(10u * scale);
        } else {
            mb_font_draw_char(dst_rgba, dst_w, dst_h, cx, y, *text, r, g, b, scale);
            cx += (int)(8u * scale);
        }
        text++;
    }
}

void mb_font_draw_text_shadow(uint8_t *dst_rgba, unsigned dst_w, unsigned dst_h,
                              int x, int y, const char *text,
                              uint8_t r, uint8_t g, uint8_t b,
                              uint8_t sr, uint8_t sg, uint8_t sb,
                              unsigned scale) {
    int off;
    if (!dst_rgba || !text) return;
    if (scale == 0) scale = 1;
    off = (int)scale;
    mb_font_draw_text(dst_rgba, dst_w, dst_h, x + off, y + off, text, sr, sg, sb, scale);
    mb_font_draw_text(dst_rgba, dst_w, dst_h, x, y, text, r, g, b, scale);
}

void mb_font_draw_text_centered(uint8_t *dst_rgba, unsigned dst_w, unsigned dst_h,
                                int y, const char *text,
                                uint8_t r, uint8_t g, uint8_t b,
                                uint8_t sr, uint8_t sg, uint8_t sb,
                                unsigned scale) {
    unsigned w;
    int x;
    if (!dst_rgba || !text) return;
    if (scale == 0) scale = 1;
    w = mb_font_text_width(text, scale);
    x = (w < dst_w) ? (int)((dst_w - w) / 2u) : 0;
    mb_font_draw_text_shadow(dst_rgba, dst_w, dst_h, x, y, text, r, g, b, sr, sg, sb, scale);
}
